// ============================================================
// 選定ロジック（現在時期＋少し先。境界で途切れないよう循環）
// ============================================================
const LATE_MONTH_DAY = 20 // この日以降は「少し先」を混ぜる

function blendCandidates(currentList, nextList, isLate, max) {
  const out = [...currentList]
  if (isLate) {
    for (const item of nextList) {
      if (out.length >= max) break
      if (!out.some(x => x.n === item.n)) out.push(item)
    }
  }
  return out.slice(0, max)
}

// 季節の候補（今の月＋月後半なら翌月を少し混ぜる）
export function getSeasonCandidates(date = new Date()) {
  const m = date.getMonth() + 1
  const d = date.getDate()
  const cur = MONTH_SEASON_CANDIDATES[m] || []
  const nxt = MONTH_SEASON_CANDIDATES[nextMonth(m)] || []
  return blendCandidates(cur, nxt, d >= LATE_MONTH_DAY, 7)
}

// 行事の候補（今の月＋月後半なら翌月・年度順で少し混ぜる）
export function getEventCandidates(date = new Date()) {
  const m = date.getMonth() + 1
  const d = date.getDate()
  const cur = MONTH_EVENT_CANDIDATES[m] || []
  const nxt = MONTH_EVENT_CANDIDATES[nextFiscalMonth(m)] || []
  return blendCandidates(cur, nxt, d >= LATE_MONTH_DAY, 8)
}

// 祝日の候補（今の月＋翌月に該当する祝日）
export function getHolidayCandidates(date = new Date()) {
  const m = date.getMonth() + 1
  const months = [m, nextMonth(m)]
  return HOLIDAYS.filter(h => months.includes(h.month))
}

// 季節・暦の行事の候補（今の月＋翌月に該当）
export function getCalendarEventCandidates(date = new Date()) {
  const m = date.getMonth() + 1
  const months = [m, nextMonth(m)]
  return CALENDAR_EVENTS.filter(e => e.months.some(x => months.includes(x)))
}

// 祝日を年度順（4月→3月）でグルーピング（「もっと見る」用。無い月は holidays:[]）
export function getHolidaysByFiscalMonth() {
  return FISCAL_MONTHS.map(month => ({
    month,
    holidays: HOLIDAYS.filter(h => h.month === month),
    none: HOLIDAY_FREE_MONTHS.includes(month),
  }))
}
